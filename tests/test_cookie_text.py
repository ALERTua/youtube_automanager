"""Tests of the cookie text functions: the line check, the login expiry and the guarded merge. All values are fake."""

import datetime
import urllib.request

import pytest

from youtube_automanager.youtube.cookie_text import (
    LOGIN_COOKIES,
    checked_lines,
    cookies,
    earliest_login_expiry,
    from_cookiejar,
    merge_known,
    to_cookiejar,
)

EXPORTED = 1_791_000_000
DAY = 24 * 60 * 60


def line(name, value, expires=EXPORTED + 400 * DAY, *, domain=".youtube.com", secure="TRUE", http_only=False):
    flag = "TRUE" if domain.startswith(".") else "FALSE"
    prefix = "#HttpOnly_" if http_only else ""
    return f"{prefix}{domain}\t{flag}\t/\t{secure}\t{expires}\t{name}\t{value}"


def text(*lines, header="# Netscape HTTP Cookie File"):
    return "\n".join([header, *lines]) + "\n"


# The shape of a fresh Firefox export: cookies that live minutes, expired ST-* cookies, a session cookie, and login
# cookies that live 365 and 400 days.
STORED = text(
    "# https://curl.haxx.se/rfc/cookie_spec.html",
    "",
    line("GPS", "fake-gps", EXPORTED + 30 * 60),
    line("YSC", "fake-ysc", 0),
    line("VISITOR_INFO1_LIVE", "fake-visitor", EXPORTED + 180 * DAY),
    line("PREF", "f6=40000000", EXPORTED + 400 * DAY),
    line("__Secure-1PSIDTS", "fake-1psidts", EXPORTED + 365 * DAY),
    line("SAPISID", "fake-sapisid"),
    line("SID", "fake-sid", secure="FALSE"),
    line("LOGIN_INFO", "fake-login-info", http_only=True),
    line("SIDCC", "fake-sidcc-old", EXPORTED + 365 * DAY, secure="FALSE"),
    line("__Secure-3PSIDCC", "fake-3psidcc-old", EXPORTED + 365 * DAY),
    line("ST-fake1", "fake-st", EXPORTED - 10, secure="FALSE"),
    line("CONSISTENCY", "fake-consistency", EXPORTED + 10 * 60),
)


def candidate(**changes):
    """The stored cookies as yt-dlp saves its jar, with ``changes`` as {name: (value, expires)} or {name: None}."""
    lines = []
    for cookie in cookies(STORED):
        change = changes.get(cookie.name, ...)
        if change is None:
            continue
        value, expires = (cookie.value, cookie.expires) if change is ... else change
        lines.append(line(cookie.name, value, expires, secure="TRUE" if cookie.secure else "FALSE"))
    return text(*lines, header="# Netscape HTTP Cookie File\n# This file is generated by yt-dlp.  Do not edit.\n")


def values(cookie_text):
    return {cookie.name: cookie.value for cookie in cookies(cookie_text)}


# The line check


def test_checked_lines_refuses_a_text_without_the_header_line():
    with pytest.raises(ValueError, match="does not start with the header line"):
        checked_lines(line("SID", "secret-value"))


@pytest.mark.parametrize(
    "bad",
    [
        ".youtube.com\tTRUE\t/\tTRUE\t1893456000\tSAPISID",
        ".youtube.com\tTRUE\t/\tTRUE\tsoon\tSAPISID\tsecret-value",
        ".youtube.com\tFALSE\t/\tTRUE\t1893456000\tSAPISID\tsecret-value",
    ],
    ids=["six fields", "bad expiry", "domain flag"],
)
def test_checked_lines_names_only_the_line_number(bad):
    with pytest.raises(ValueError, match="line 3 of the cookie text") as raised:
        checked_lines(text("", bad))

    assert "secret-value" not in str(raised.value)


def test_cookies_reads_each_field_and_the_httponly_mark():
    parsed = {cookie.name: cookie for cookie in cookies(STORED)}

    assert parsed["LOGIN_INFO"].http_only
    assert not parsed["SID"].http_only
    assert (parsed["SID"].domain, parsed["SID"].path, parsed["SID"].secure) == (".youtube.com", "/", False)
    assert parsed["YSC"].expires == 0
    assert parsed["GPS"].expires == EXPORTED + 30 * 60


# The expiry date of the login


def test_earliest_login_expiry_counts_only_the_login_cookies():
    # GPS, CONSISTENCY and ST-* expire within minutes, and VISITOR_INFO1_LIVE after 180 days.
    assert earliest_login_expiry(STORED) == datetime.datetime.fromtimestamp(EXPORTED + 365 * DAY, datetime.UTC)


def test_earliest_login_expiry_without_a_dated_login_cookie_is_none():
    assert earliest_login_expiry(text(line("SID", "fake-sid", 0), line("GPS", "fake-gps"))) is None
    assert earliest_login_expiry("SID=fake") is None


def test_earliest_login_expiry_skips_a_line_that_is_not_a_cookie_line():
    broken = text("not a cookie line", line("SAPISID", "fake-sapisid", EXPORTED))

    assert earliest_login_expiry(broken) == datetime.datetime.fromtimestamp(EXPORTED, datetime.UTC)


def test_login_cookies_hold_the_cookies_that_yt_dlp_signs_the_requests_with():
    assert {"SAPISID", "__Secure-1PAPISID", "__Secure-3PAPISID", "LOGIN_INFO"} <= LOGIN_COOKIES


# The guarded merge


def test_merge_takes_the_new_values_of_known_cookies():
    later = EXPORTED + 500 * DAY
    merged = merge_known(
        STORED, candidate(SIDCC=("fake-sidcc-new", later), **{"__Secure-3PSIDCC": ("fake-3new", later)})
    )

    assert merged.changed == ("SIDCC", "__Secure-3PSIDCC")
    assert values(merged.text) == values(STORED) | {"SIDCC": "fake-sidcc-new", "__Secure-3PSIDCC": "fake-3new"}
    assert {c.name: c.expires for c in cookies(merged.text)}["SIDCC"] == later


def test_merge_never_takes_a_removal():
    # A read check removes the ST-* cookies, and the jar drops expired cookies such as CONSISTENCY.
    removed = candidate(**{"ST-fake1": None, "CONSISTENCY": None, "GPS": None, "LOGIN_INFO": None, "SAPISID": None})

    merged = merge_known(STORED, removed)

    assert merged == merge_known(STORED, STORED)
    assert merged.changed == ()
    assert merged.text == STORED


def test_merge_never_takes_a_new_cookie_name():
    new_name = candidate() + line("__Secure-NEW", "fake-new") + "\n"

    merged = merge_known(STORED, new_name)

    assert merged.changed == ()
    assert "__Secure-NEW" not in values(merged.text)


def test_merge_never_takes_the_pref_that_yt_dlp_sets():
    merged = merge_known(STORED, candidate(PREF=("hl=en&tz=UTC", EXPORTED + 400 * DAY)))

    assert merged.changed == ()
    assert values(merged.text)["PREF"] == "f6=40000000"


def test_merge_never_takes_an_empty_value():
    stored = text(line("SIDCC", "fake-sidcc-old"))

    merged = merge_known(stored, text(line("SIDCC", "")))

    assert merged.changed == ()
    assert merged.text == stored


def test_merge_keeps_an_earlier_expiry_and_a_session_cookie_without_a_date():
    earlier = EXPORTED + 10 * DAY
    merged = merge_known(STORED, candidate(SIDCC=("fake-sidcc-new", earlier), YSC=("fake-ysc-new", EXPORTED + DAY)))

    expires = {c.name: c.expires for c in cookies(merged.text)}
    assert merged.changed == ("YSC", "SIDCC")
    assert expires["SIDCC"] == EXPORTED + 365 * DAY
    assert expires["YSC"] == 0


def test_merge_ignores_a_later_expiry_without_a_new_value():
    merged = merge_known(STORED, candidate(SID=("fake-sid", EXPORTED + 900 * DAY)))

    assert merged.changed == ()
    assert merged.text == STORED


def test_merge_keeps_the_comments_the_order_and_the_httponly_mark():
    merged = merge_known(STORED, candidate(LOGIN_INFO=("fake-login-new", EXPORTED + 400 * DAY)))

    expected = STORED.replace("fake-login-info", "fake-login-new")
    assert merged.text == expected
    assert merged.changed == ("LOGIN_INFO",)


def test_merge_matches_a_cookie_by_its_domain_and_path():
    host_only = candidate() + line("SIDCC", "fake-host-only", domain="www.youtube.com") + "\n"

    assert merge_known(STORED, host_only).changed == ()


def test_merge_of_a_stored_text_with_crlf_line_ends():
    stored = STORED.replace("\n", "\r\n")

    merged = merge_known(stored, candidate(SIDCC=("fake-sidcc-new", EXPORTED + 400 * DAY)))

    assert merged.changed == ("SIDCC",)
    assert "\r" not in merged.text


def test_merge_refuses_a_candidate_that_is_not_a_cookie_file():
    with pytest.raises(ValueError, match="does not start with the header line"):
        merge_known(STORED, "SIDCC=fake")


# The standard cookie jar


def test_a_standard_jar_keeps_each_cookie_and_writes_it_back():
    jar = to_cookiejar(STORED)

    assert values(from_cookiejar(jar)) == values(STORED)
    assert merge_known(STORED, from_cookiejar(jar)).changed == ()


def test_a_standard_jar_sends_the_domain_cookies_to_accounts_youtube_com_and_drops_the_expired_ones():
    far = 4_000_000_000
    jar = to_cookiejar(
        text(
            line("SAPISID", "fake-sapisid", far),
            line("LOGIN_INFO", "fake-login-info", far, http_only=True),
            line("YSC", "fake-ysc", 0),
            line("ST-fake1", "fake-st", EXPORTED - 10, secure="FALSE"),
            line("HSID", "fake-hsid", far, domain="www.youtube.com"),
        )
    )
    request = urllib.request.Request("https://accounts.youtube.com/RotateCookiesPage")

    jar.add_cookie_header(request)

    sent = dict(part.split("=", 1) for part in request.get_header("Cookie").split("; "))
    assert sent == {"SAPISID": "fake-sapisid", "LOGIN_INFO": "fake-login-info", "YSC": "fake-ysc"}
    assert set(values(from_cookiejar(jar))) == {"SAPISID", "LOGIN_INFO", "YSC", "HSID"}


def test_a_written_jar_leaves_out_a_value_with_a_tab_or_a_line_break():
    jar = to_cookiejar(text(line("SIDCC", "fake-sidcc"), line("SID", "fake-sid"), line("HSID", "fake-hsid")))
    for cookie in jar:
        cookie.value = {"SIDCC": "fake\tvalue", "HSID": "fake\nvalue"}.get(cookie.name, cookie.value)

    assert values(from_cookiejar(jar)) == {"SID": "fake-sid"}
